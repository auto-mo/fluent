import AppKit
import ApplicationServices
import CoreGraphics

/// Puts dictated text into the focused text box.
/// 1. Typed in directly through Accessibility, then read back to confirm. The clipboard is not touched.
/// 2. Only if the app refuses that, or the result can't be confirmed: pasted through the clipboard,
///    marked so clipboard managers skip it, and the previous clipboard put back.
@MainActor
enum Inserter {
    enum Method: String { case typed = "Typed directly", pasted = "Pasted (clipboard restored)" }

    /// Returns when the text went in and how, or nil if there was nothing to insert.
    static func insert(_ text: String) async -> (date: Date, method: Method)? {
        guard !text.isEmpty else { return nil }
        let front = NSWorkspace.shared.frontmostApplication
        let pid = front?.processIdentifier
        // Apps that accepted direct typing but ignored it earlier this session go straight to paste.
        if let id = front?.bundleIdentifier, pasteOnly.contains(id) {
            return await paste(text).map { ($0, .pasted) }
        }
        // Accessibility calls block until the other app answers, so keep them off the main thread.
        // Fluent's own windows are the exception: macOS handles those in-process, on the calling
        // thread, so they must run on the main thread (only the --insert-test check does this).
        let outcome: DirectOutcome = if let pid {
            pid == ProcessInfo.processInfo.processIdentifier
                ? directInsert(text, pid: pid)
                : await Task.detached { directInsert(text, pid: pid) }.value
        } else { .notSupported }
        switch outcome {
        case .inserted: return (.now, .typed)
        case .changedUnexpectedly: return (.now, .typed)   // something went in; pasting too could double it
        case .notSupported:
            if let id = front?.bundleIdentifier { pasteOnly.insert(id) }
            return await paste(text).map { ($0, .pasted) }
        }
    }

    enum DirectOutcome: Sendable { case inserted, notSupported, changedUnexpectedly }

    /// Bundle IDs that ignored direct typing this session.
    private static var pasteOnly: Set<String> = []

    nonisolated static func directInsert(_ text: String, pid: pid_t) -> DirectOutcome {
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, 0.5)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let ref = focused, CFGetTypeID(ref) == AXUIElementGetTypeID() else { return .notSupported }
        let element = ref as! AXUIElement

        var settable: DarwinBoolean = false
        guard AXUIElementIsAttributeSettable(element, kAXSelectedTextAttribute as CFString, &settable) == .success,
              settable.boolValue, let before = value(of: element) else { return .notSupported }

        guard AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFString) == .success
        else { return .notSupported }

        // Some apps report success without inserting anything, and some update what they report a
        // little later. Watch for the change briefly before deciding. (Claude, for one, accepts the
        // request and inserts nothing; it then gets the clipboard paste.)
        for _ in 0..<6 {
            guard let after = value(of: element) else { return .changedUnexpectedly }
            if after != before { return after.contains(text) ? .inserted : .changedUnexpectedly }
            usleep(50_000)
        }
        return .notSupported
    }

    private nonisolated static func value(of element: AXUIElement) -> String? {
        var v: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &v) == .success else { return nil }
        return v as? String
    }

    // MARK: Clipboard fallback

    private struct SavedItem { let types: [(NSPasteboard.PasteboardType, Data)] }
    /// nspasteboard.org markers that clipboard managers (Maccy, Paste, Raycast, Alfred) honour.
    private static let skipMarkers = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
                                      "org.nspasteboard.AutoGeneratedType"].map { NSPasteboard.PasteboardType(rawValue: $0) }

    /// Returns when ⌘V was sent.
    @discardableResult
    static func paste(_ text: String) async -> Date? {
        let pb = NSPasteboard.general
        let saved = pb.pasteboardItems?.map { item in
            SavedItem(types: item.types.compactMap { t in item.data(forType: t).map { (t, $0) } })
        } ?? []

        // How much text the box holds now, so we can see when the paste has actually landed.
        let pid = NSWorkspace.shared.frontmostApplication?.processIdentifier
        let countBefore: Int? = if let pid { await Task.detached { characterCount(pid: pid) }.value } else { nil }

        pb.clearContents()
        pb.setString(text, forType: .string)
        for marker in skipMarkers { pb.setString("", forType: marker) }
        let ours = pb.changeCount

        postCommandV()
        let pasted = Date.now

        // Only put the old clipboard back once the app has read ours. A busy app (Claude, for one)
        // can handle ⌘V late; restoring too early made it paste the old clipboard instead.
        if let pid, countBefore != nil {
            var landed = false
            for _ in 0..<40 {   // up to 2 s
                try? await Task.sleep(for: .milliseconds(50))
                let now = await Task.detached { characterCount(pid: pid) }.value
                if let now, now != countBefore { landed = true; break }
            }
            try? await Task.sleep(for: .milliseconds(landed ? 150 : 0))
        } else {
            try? await Task.sleep(for: .seconds(1))   // can't see the box: allow plenty of time
        }
        guard pb.changeCount == ours else { return pasted }   // something else wrote to it meanwhile; leave it
        pb.clearContents()
        let items = saved.map { s -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in s.types { item.setData(data, forType: type) }
            // The restore is a copy of what was already there; keep managers from listing it twice.
            for marker in skipMarkers where !s.types.contains(where: { $0.0 == marker }) { item.setString("", forType: marker) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
        return pasted
    }

    /// Number of characters in the focused text box of an app, or nil when it doesn't say.
    nonisolated static func characterCount(pid: pid_t) -> Int? {
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, 0.2)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let ref = focused, CFGetTypeID(ref) == AXUIElementGetTypeID() else { return nil }
        var n: CFTypeRef?
        if AXUIElementCopyAttributeValue(ref as! AXUIElement, kAXNumberOfCharactersAttribute as CFString, &n) == .success,
           let count = n as? Int { return count }
        var v: CFTypeRef?
        guard AXUIElementCopyAttributeValue(ref as! AXUIElement, kAXValueAttribute as CFString, &v) == .success,
              let s = v as? String else { return nil }
        return s.utf16.count
    }

    /// Sends one key press with optional ⌘ to the app in front.
    static func postKey(_ key: CGKeyCode, command: Bool) {
        let src = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: false)
        if command { down?.flags = .maskCommand; up?.flags = .maskCommand }
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private static func postCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        // Ignore keys the person is still holding (such as the dictation key) so the paste is a plain ⌘V.
        src?.setLocalEventsFilterDuringSuppressionState([.permitLocalMouseEvents, .permitSystemDefinedEvents],
                                                        state: .eventSuppressionStateSuppressionInterval)
        let vKey: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
